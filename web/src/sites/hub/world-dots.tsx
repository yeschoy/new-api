/** Dotted world map used behind the light hero (drawn, not an image). */
export function WorldDots(props: { className?: string }) {
  const dots = useMemo(() => {
    const out: Array<[number, number]> = []
    MAP.forEach((row, y) => {
      for (let x = 0; x < row.length; x += 1) {
        if (row[x] !== '#') continue
        // Two dots per cell horizontally for the dense stipple look.
        out.push([x * 2, y * 2], [x * 2 + 1, y * 2], [x * 2, y * 2 + 1], [x * 2 + 1, y * 2 + 1])
      }
    })
    return out
  }, [])

  return (
    <svg
      viewBox='0 0 180 68'
      preserveAspectRatio='xMidYMid meet'
      aria-hidden='true'
      className={props.className}
    >
      {dots.map(([x, y]) => (
        <circle key={`${x}-${y}`} cx={x + 0.5} cy={y + 0.5} r={0.24} fill='currentColor' />
      ))}
    </svg>
  )
}
